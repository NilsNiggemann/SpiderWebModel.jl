using Stencils, BenchmarkTools, StaticArrays
function P_applicable(Pij, M::Integer)
    S6, S7, S8, S5, S1, S4, S3, S2 = Pij
    v = (S1, -S2, -S3, S4, S5, -S6, -S7, S8)

    p = all(<(M), v)
    pdagger = all(>(-M), v)
    return p, pdagger
end

function plaquetteIterator(S::AbstractMatrix)
    inboundsInds = Base.Iterators.product(axes(S, 1)[begin+1:end-1], axes(S, 2)[begin+1:end-1])
    filterInds = Iterators.filter(ind -> isodd(sum(ind)), inboundsInds)
end


function NPlaquettes(Conf)
    moves = 0
    for I in plaquetteIterator(Conf)
        Pij = Stencils.stencil(Conf, I)
        applPlus, applMinus = P_applicable(Pij, 2)
        moves += applPlus + applMinus
    end
    return moves
end


